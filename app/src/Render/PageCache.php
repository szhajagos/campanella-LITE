<?php

declare(strict_types=1);

namespace Campanella\Lite\Render;

use Campanella\Lite\Exception\StorageException;
use Campanella\Lite\Routing\Urls;
use Campanella\Lite\Storage\FileStore;

/**
 * Generated pages in the web root, and the manifest that lists them.
 *
 * Every file the generator writes is recorded in var/cache-manifest.json.
 * Clearing the cache deletes exactly those files, so nothing else in the
 * web root (the front controller, assets, files put there by hand) is
 * ever touched. The generator also refuses to overwrite a file it did not
 * create.
 */
final class PageCache
{
    public const MANIFEST = 'cache-manifest.json';

    public function __construct(
        private readonly FileStore $public,
        private readonly FileStore $var,
    ) {
    }

    /**
     * Stores the HTML of a page address and returns the file it was written to.
     */
    public function store(string $path, string $html): string
    {
        $file = Urls::file($path);
        $files = $this->files();

        if (!in_array($file, $files, true) && $this->public->exists($file)) {
            throw StorageException::unsafePath($file, 'the file exists and was not generated by Campanella Lite');
        }

        $this->public->write($file, $html);

        if (!in_array($file, $files, true)) {
            $files[] = $file;
            $this->saveManifest($files);
        }

        return $file;
    }

    /**
     * Deletes every generated file and returns how many there were.
     */
    public function clear(): int
    {
        $files = $this->files();
        $deleted = 0;

        foreach ($files as $file) {
            if ($this->public->delete($file)) {
                $deleted++;
            }

            $this->removeEmptyParents($file);
        }

        $this->saveManifest([]);

        return $deleted;
    }

    /**
     * @return list<string> generated files, relative to the web root
     */
    public function files(): array
    {
        if (!$this->var->exists(self::MANIFEST)) {
            return [];
        }

        $data = json_decode($this->var->read(self::MANIFEST), true);

        return is_array($data) ? array_values(array_filter($data, 'is_string')) : [];
    }

    /**
     * @param list<string> $files
     */
    private function saveManifest(array $files): void
    {
        sort($files);
        $this->var->write(self::MANIFEST, json_encode($files, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR) . "\n");
    }

    private function removeEmptyParents(string $file): void
    {
        $directory = dirname($file);

        while ($directory !== '.' && $directory !== '' && $this->public->deleteDirectoryIfEmpty($directory)) {
            $directory = dirname($directory);
        }
    }
}
